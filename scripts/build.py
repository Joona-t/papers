    toc_items = f'<a class="toc-start" href="#start">How to use this archive</a><ol class="toc-parts">{"".join(toc)}</ol>'
    nav = "".join(f'<a href="#{f["id"]}">{esc(f["nav"])}</a>' for f in data["fields"])
